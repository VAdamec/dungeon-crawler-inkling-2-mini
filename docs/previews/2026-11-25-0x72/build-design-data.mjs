import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const tileList = fs.readFileSync(path.join(root, 'assets/source/0x72-dungeontileset-ii-v1.7/tile_list_v1.7'), 'utf8')
  .trim().split(/\n/).filter(Boolean)
  .map(line => {
    const [name, x, y, w, h] = line.trim().split(/\s+/);
    return { name, x: +x, y: +y, w: +w, h: +h };
  });

const crops = {};
for (const t of tileList) crops[t.name] = [t.x, t.y, t.w, t.h];

const inv = JSON.parse(fs.readFileSync(path.join(root, 'docs/previews/2026-11-25-0x72/runtime-inventory.json'), 'utf8'));
const assets = inv.assets; // One mapping source: build-data.mjs → runtime-inventory.json.

const counts = {};
for (const a of assets) counts[a.status] = (counts[a.status] || 0) + 1;

const out = `/* Generated by build-design-data.mjs — do not edit by hand. */
window.DESIGN_DATA = ${JSON.stringify({ crops, assets, counts, cropCount: tileList.length }, null, 0)};
`;
fs.writeFileSync(path.join(root, 'docs/previews/2026-11-25-0x72/design-v2-data.js'), out);
console.log('wrote', assets.length, 'roles', tileList.length, 'crops', counts);
